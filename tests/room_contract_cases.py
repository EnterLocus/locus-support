"""Source mutations and expected outcomes for public Room contract fixtures.

Each case starts with ``room_fixtures.minimal_room()``.  The resulting flat and
Package v2 archives are generated by ``tools/export_room_contract_fixtures.py``;
no archive is checked into the repository.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Optional

import room_fixtures


Mutation = Callable[[room_fixtures.Room], None]


@dataclass(frozen=True)
class ContractCase:
    """One deterministic Room source mutation and its public expectations."""

    identifier: str
    description: str
    mutate: Mutation
    importer_outcome: str
    importer_error: Optional[str]
    entry_outcome: str
    entry_error: Optional[str]
    checker_e_code: Optional[str]
    intentional_difference: Optional[str] = None
    uncertainty: Optional[str] = None

    def room(self) -> room_fixtures.Room:
        return room_fixtures.minimal_room(self.mutate)

    def annotation(self) -> dict:
        result = {
            "expectation": "expected-app-behavior",
            "importer": {"outcome": self.importer_outcome, "error": self.importer_error},
            "entry": {"outcome": self.entry_outcome, "error": self.entry_error},
            "checker": {"expectedECode": self.checker_e_code},
        }
        if self.intentional_difference is not None:
            result["intentionalDifference"] = self.intentional_difference
        if self.uncertainty is not None:
            result["uncertainty"] = self.uncertainty
        return result


def missing_binding(room: room_fixtures.Room) -> None:
    room.space["spatialAdaptation"]["roofEntities"] = ["Roof_MISSING"]


def tilted_seated_origin(room: room_fixtures.Room) -> None:
    room.space["seatedOrigin"]["orientationXYZW"] = [0.1, 0, 0, 0.995]


def zero_seated_origin(room: room_fixtures.Room) -> None:
    room.space["seatedOrigin"]["orientationXYZW"] = [0, 0, 0, 0]


def nonemissive_luminaire(room: room_fixtures.Room) -> None:
    room.materials["Lamp_Glow"] = ((1.0, 0.64, 0.30), 0.5, None, 1.0)


def add_nonopaque_illuminated(room: room_fixtures.Room) -> None:
    room.space["formatVersion"] = 8
    room.materials["Illuminated_Glow"] = ((1.0, 0.64, 0.30), 0.5, (1.0, 0.64, 0.30), 0.5)
    room.boxes.append({
        "name": "Illuminated_Panel", "center": (0, 2.0, 0), "size": (0.4, 0.1, 0.4),
        "material": "Illuminated_Glow",
    })
    room.space["lighting"]["luminaireGroups"][0]["illuminatedEntities"] = ["Illuminated_Panel"]


def add_nonopaque_baked_indirect(room: room_fixtures.Room) -> None:
    room.materials["Indirect_Glow"] = ((1.0, 0.64, 0.30), 0.5, (1.0, 0.64, 0.30), 0.5)
    room.boxes.append({
        "name": "Indirect_Panel", "center": (0, 2.0, 0), "size": (0.4, 0.1, 0.4),
        "material": "Indirect_Glow",
    })
    room.space["lighting"]["bakedIndirect"] = {"entities": ["Indirect_Panel"]}


def missing_animation(room: room_fixtures.Room) -> None:
    room.space["ambientAnimations"] = [{
        "id": "missing-animation",
        "displayName": "Missing Animation",
        "entityName": "Pendant_Glow",
        "animationName": "missing",
        "isEnabledByDefault": True,
        "defaultSpeed": 1.0,
        "speedRange": [0.5, 1.5],
        "defaultIntervalRangeSeconds": [0, 0],
        "intervalRangeSeconds": [0, 10],
    }]


def desk_outside_group(room: room_fixtures.Room) -> None:
    room.space["spatialAdaptation"]["deskGroupEntitiesByTeleportID"] = {
        room_fixtures.SEAT_ID: "Chair_Seat",
    }


def zero_thickness_desk(room: room_fixtures.Room) -> None:
    room.box("Table_Top")["size"] = (1.5, 0.0, 0.7)


def degenerate_bounds(room: room_fixtures.Room) -> None:
    floor = room.box("Floor")
    floor["size"] = (0.0, 0.0, 0.0)
    room.boxes = [floor]


def no_seats(room: room_fixtures.Room) -> None:
    room.seats = []


CASES = (
    ContractCase("valid", "Valid Room baseline.", lambda room: None,
                 "accept", None, "accept", None, None),
    ContractCase("missingbinding", "A referenced roof entity is absent from the model.", missing_binding,
                 "reject", "missingAdaptationEntity", "reject", "missingAdaptationEntity", "binding"),
    ContractCase("tilted-seated-origin", "The seated-origin quaternion tilts the Room.", tilted_seated_origin,
                 "accept", None, "reject", "invalidModelBounds", "seatedOrigin"),
    ContractCase("zero-seated-origin", "The seated-origin quaternion is zero.", zero_seated_origin,
                 "accept", None, "reject", "invalidModelBounds", "seatedOrigin"),
    ContractCase("nonemissive-luminaire", "A declared luminaire has no positive emission.", nonemissive_luminaire,
                 "accept", None, "reject", "entityHasNoPositiveEmissive", "entityHasNoPositiveEmissive"),
    ContractCase("nonopaque-illuminated", "A separate illuminated subtree has nonopaque positive emission.", add_nonopaque_illuminated,
                 "accept", None, "reject", "illuminatedEntityIsNotOpaque", "nonOpaqueEmission"),
    ContractCase("nonopaque-baked-indirect", "A baked-indirect entity has nonopaque emission.", add_nonopaque_baked_indirect,
                 "accept", None, "reject", "indirectMaterialIsNotOpaque", "nonOpaqueEmission"),
    ContractCase("missing-animation", "A declared animation clip is absent from its entity.", missing_animation,
                 "accept", None, "reject", "missingAnimation", "missingAnimation"),
    ContractCase("desk-outside-group", "The desk surface is not below its Hide Desk group.", desk_outside_group,
                 "accept", None, "reject", "deskGroupSurfaceMismatch", "deskGroupSurfaceMismatch"),
    ContractCase("zero-thickness-desk", "The desktop has zero visual thickness.", zero_thickness_desk,
                 "accept", None, "accept", None, "deskBounds",
                 "Intentional conservative checker difference: the reader accepts a zero-thickness desk, while the checker requires three nondegenerate visual extents."),
    ContractCase("degenerate-bounds", "The model has degenerate visual bounds.", degenerate_bounds,
                 "accept", None, "reject", "invalidModelBounds", "invalidModelBounds", None,
                 "The source exporter does not run the app installer or enter a Room; app-stage parity is verified by the app consumer."),
    ContractCase("no-seats", "The Room declares no teleport points.", no_seats,
                 "accept", None, "reject", "missingTeleportPoints", "missingTeleportPoints", None,
                 "Public structural validators reject an empty teleport catalog before entry; the app importer and entry-stage boundary remains for the app consumer to verify."),
)


def case_by_id(identifier: str) -> ContractCase:
    for case in CASES:
        if case.identifier == identifier:
            return case
    raise KeyError(identifier)
